// Root & Pattern layer (الجذر والوزن).
//
// Arabic vocabulary is not a list of unrelated words. Almost every word is a
// three-letter root (الجذر) poured into a pattern (الوزن). Learn a few patterns
// and you can often guess a word you have never seen.
//
//   ك-ت-ب  = the idea of "writing"
//   مَفْعَل  = "the place where ..."   ->  مَكْتَب   = desk / office
//   فَاعِل   = "the one who ..."       ->  كَاتِب   = writer
//   مَفْعُول = "the one that was ..."  ->  مَكْتُوب = written
//
// This file owns the linguistics. Words in lessonData.js pick up their root and
// pattern automatically via WORD_MORPHOLOGY, keyed on a normalised spelling.

// Normalise an Arabic spelling so lookups survive optional diacritics and the
// usual alef/ya/ta-marbuta variants. Both sides of a lookup go through this.
function normArabic(value) {
    return String(value || '')
        .replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g, '')
        .replace(/[\u0622\u0623\u0625\u0671]/g, '\u0627')
        .replace(/\u0649/g, '\u064A')
        .replace(/\u0629/g, '\u0647')
        .replace(/\s+/g, ' ')
        .trim();
}

