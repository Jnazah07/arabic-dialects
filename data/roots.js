// Portuguese-style flat index: normalised Arabic spelling -> morphology.
// lessonData.js reads this when it builds each word object.
const WORD_MORPHOLOGY = {};
ROOT_FAMILIES.forEach(family => {
    family.forms.forEach(form => {
        const key = normArabic(form.ar);
        if (!WORD_MORPHOLOGY[key]) {
            WORD_MORPHOLOGY[key] = {
                root: family.root,
                rootMeaning: family.meaning,
                pattern: form.pattern,
                patternLatin: form.latin,
                role: form.role
            };
        }
    });
});

// Flat, de-duplicated list of every form, used by the inference drill.
const ROOT_FORM_LIST = (() => {
    const seen = new Set();
    const list = [];
    ROOT_FAMILIES.forEach(family => {
        family.forms.forEach(form => {
            const key = normArabic(form.ar);
            if (seen.has(key)) return;
            seen.add(key);
            list.push({
                ar: form.ar,
                tr: form.tr,
                en: form.en,
                root: family.root,
                rootMeaning: family.meaning,
                pattern: form.pattern,
                patternLatin: form.latin,
                patternRole: form.role
            });
        });
    });
    return list;
})();
